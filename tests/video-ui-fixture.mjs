// Isolated local UI verification. No native harnesses, credentials or model calls.
import {createHub} from '../src/server.mjs';
import {PROVIDERS} from '../src/providers.mjs';
import {mkdtempSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {parseVideoReference} from '../src/videos.mjs';
const registry={resolve:()=>({command:process.execPath,prefixArgs:[]}),probe:async()=>({}),record:()=>{},models:async()=>({models:[]}),list:async()=>Object.values(PROVIDERS).map(p=>({...p,installed:true,statusLabel:'隔离测试环境 · 模拟视频'}))};
const fake=async({prompt,emit})=>emit({type:'replace',text:prompt.includes('模拟字幕：回购和分红')?'模拟模型已收到带时间戳的视频字幕。':'模拟模型未收到字幕。'});
const hub=createHub({port:3215,dataDir:mkdtempSync(join(tmpdir(),'starport-video-ui-')),registry,implementations:Object.fromEntries(Object.keys(PROVIDERS).map(p=>[p,fake]))});
hub.edge.status=()=>({paired:true,connected:true});
hub.edge.video=async reference=>{
  const {bvid,part}=parseVideoReference(reference);await new Promise(resolve=>setTimeout(resolve,bvid==='BV0000000002'?4000:400));
  if(bvid==='BV0000000001')return {status:'no_subtitles',bvid,part};
  return {status:'ok',bvid,part,title:'隔离测试视频',duration:1160,language:'中文',isAutoGenerated:true,segments:[{from:0,to:10,content:'模拟字幕：回购和分红'},{from:10,to:30,content:'<img src=x onerror="window.__videoXss=true">'}]};
};
await hub.listen();console.log('Video UI fixture: http://127.0.0.1:3215 (all four providers simulated)');
