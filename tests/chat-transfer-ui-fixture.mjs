import { createHub } from '../src/server.mjs';
import { ChatTransfer } from '../src/chat-transfer.mjs';
import { PROVIDERS } from '../src/providers.mjs';
import { fixtureHistoryConnect } from './fixtures/history.mjs';
import { fixtureClaudeHistory } from './fixtures/claude-history.mjs';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const dir = await mkdtemp(join(tmpdir(), 'starport-transfer-ui-'));
const registry = { resolve: () => null, models: async () => ({ models: [] }), list: async () => Object.values(PROVIDERS).map(row => ({ ...row, installed: false, statusLabel: '隔离测试环境' })), verifications: () => ({}) };
const hub = createHub({ dataDir: dir, port: 0, registry, historyConnect: fixtureHistoryConnect(), claudeHistory: fixtureClaudeHistory() });
const chat = hub.store.newChat({ title: '跨电脑迁移测试', workspace: dir, provider: 'claude', group_id: hub.store.group('测试分组').id });
const attachment = await hub.attachments.upload({ name: 'example.md', data: Buffer.from('# Hello Starport\n$E=mc^2$').toString('base64') });
hub.store.message(chat.id, 'user', 'claude', '请读取示例文件。', 'complete', { attachments: [attachment] });
hub.store.message(chat.id, 'assistant', 'claude', '文件已读取，这是用于迁移测试的示例回复。', 'complete', { activity: [{ id: 'read-file', kind: 'tool', title: 'Read', status: 'complete', output: '# Hello Starport' }] });
const transfer = new ChatTransfer(hub.store, hub.attachments);
const file = join(dir, 'example.starport.json'); await writeFile(file, JSON.stringify(transfer.export(chat.id)));
const port = await hub.listen(); console.log(JSON.stringify({ port, file, dir, chatId: chat.id }));
process.on('SIGINT', async () => { await hub.close(); process.exit(0); });
