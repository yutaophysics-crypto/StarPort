'use strict';
// Self-contained: Chrome serializes this function into the requested Bilibili tab.
// Login stays in Edge. Only validated metadata and subtitle text leave the tab.
async function readBiliVideo({bvid,part}){
  if(!/^BV[0-9A-Za-z]{10}$/.test(bvid)||!Number.isSafeInteger(part)||part<1||part>1000||location.hostname!=='www.bilibili.com')throw Error('视频请求无效');
  const fail=status=>({status,bvid,part});
  async function json(url,credentials,maxBytes){
    let response;try{response=await fetch(url,{credentials,redirect:'error',signal:AbortSignal.timeout(8000)});}catch{throw Error('B 站字幕网络请求失败，请稍后重试');}
    if(!response.ok)throw Error('B 站字幕请求失败，请在 Edge 中检查视频是否可以播放');
    if(Number(response.headers.get('content-length'))>maxBytes)throw Error('视频字幕过长，请分段读取');
    const reader=response.body.getReader();let size=0;const chunks=[];
    for(;;){const {done,value}=await reader.read();if(done)break;size+=value.length;if(size>maxBytes){await reader.cancel();throw Error('视频字幕过长，请分段读取');}chunks.push(value);}
    const bytes=new Uint8Array(size);let offset=0;for(const chunk of chunks){bytes.set(chunk,offset);offset+=chunk.length;}
    try{return JSON.parse(new TextDecoder().decode(bytes));}catch{throw Error('B 站返回的字幕格式无效');}
  }
  const metadata=await json(`https://api.bilibili.com/x/web-interface/view?bvid=${bvid}`,'include',2000000);
  if(metadata.code!==0||metadata.data?.bvid!==bvid)return fail('unavailable');
  const data=metadata.data,page=data.pages?.[part-1];
  if(!page||!Number.isSafeInteger(page.cid)||page.cid<=0)return fail('unavailable');
  const player=await json(`https://api.bilibili.com/x/player/wbi/v2?bvid=${bvid}&cid=${page.cid}`,'include',2000000);
  if(player.code!==0)return fail('unavailable');
  const tracks=player.data?.subtitle?.subtitles;
  if(!Array.isArray(tracks)||!tracks.length)return fail(player.data?.need_login_subtitle?'login_required':'no_subtitles');
  const rank=track=>/^zh|^ai-zh/.test(track.lan||'')?(/^ai-/.test(track.lan)?1:0):2;
  const track=[...tracks].sort((a,b)=>rank(a)-rank(b))[0];
  let captionURL;try{captionURL=new URL(track.subtitle_url.startsWith('//')?'https:'+track.subtitle_url:track.subtitle_url);}catch{throw Error('B 站返回的字幕地址无效');}
  if(captionURL.protocol!=='https:'||captionURL.username||captionURL.password||captionURL.port||!/(^|\.)hdslb\.com$/.test(captionURL.hostname))throw Error('B 站返回的字幕地址无效');
  // Signed subtitle URLs remain inside the browser, and receive no login cookies.
  const captions=await json(captionURL.href,'omit',2000000),body=captions.body;
  if(!Array.isArray(body)||!body.length)return fail('no_subtitles');
  if(body.length>20000)throw Error('视频字幕过长，请分段读取');
  let length=0;const segments=body.map(row=>{if(typeof row.content!=='string'||!Number.isFinite(row.from)||!Number.isFinite(row.to))throw Error('B 站返回的字幕格式无效');length+=row.content.length;if(length>90000)throw Error('视频字幕过长，请分段读取');return {from:row.from,to:row.to,content:row.content};});
  return {status:'ok',bvid,part,title:String(data.title||bvid).slice(0,240),duration:page.duration,language:String(track.lan_doc||track.lan||'未知').slice(0,80),isAutoGenerated:/^ai-/.test(track.lan||''),segments};
}
